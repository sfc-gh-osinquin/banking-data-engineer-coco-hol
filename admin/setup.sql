-- ---------------------------------------------------------------------------
-- SECTION 2: Create the sandbox database, warehouse, stage and tables.
-- ---------------------------------------------------------------------------
CREATE DATABASE HOL_BANKING_DE COMMENT = 'Synthetic Cortex Code hands-on lab sandbox';
CREATE SCHEMA HOL_BANKING_DE.SOURCE;
CREATE WAREHOUSE HOL_BANKING_WH
  WAREHOUSE_SIZE = 'XSMALL' AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE;
CREATE FILE FORMAT HOL_BANKING_DE.SOURCE.HOL_CSV
  TYPE = CSV SKIP_HEADER = 1 FIELD_OPTIONALLY_ENCLOSED_BY = '"' ERROR_ON_COLUMN_COUNT_MISMATCH = TRUE;
CREATE STAGE HOL_BANKING_DE.SOURCE.HOL_DATA
  ENCRYPTION = (TYPE = 'SNOWFLAKE_SSE') FILE_FORMAT = HOL_BANKING_DE.SOURCE.HOL_CSV;
CREATE TABLE HOL_BANKING_DE.SOURCE.LOCATIONS (LOCATION_ID NUMBER NOT NULL, LOCATION_NAME VARCHAR NOT NULL);
CREATE TABLE HOL_BANKING_DE.SOURCE.CUSTOMERS (CUSTOMER_ID NUMBER NOT NULL, SEGMENT VARCHAR NOT NULL, LOCATION_ID NUMBER NOT NULL);
CREATE TABLE HOL_BANKING_DE.SOURCE.TRANSACTIONS (
  TRANSACTION_ID NUMBER NOT NULL, CUSTOMER_ID NUMBER NOT NULL, TRANSACTION_TIME TIMESTAMP_NTZ NOT NULL,
  AMOUNT NUMBER(12,2) NOT NULL, PRODUCT_CATEGORY VARCHAR NOT NULL, CHANNEL VARCHAR NOT NULL, STATUS VARCHAR NOT NULL);

-- ---------------------------------------------------------------------------
-- SECTION 3: Upload data (Snowsight UI, no SQL).
-- Unzip data/banking-data-engineer-coco-hol-data.zip from the lab repo. In Snowsight open
-- HOL_BANKING_DE.SOURCE.HOL_DATA and upload locations.csv, customers.csv, transactions.csv.
-- ---------------------------------------------------------------------------

-- ---------------------------------------------------------------------------
-- SECTION 4: Load and reconcile. Expected values are in the lab README.
-- ---------------------------------------------------------------------------
USE WAREHOUSE HOL_BANKING_WH;
COPY INTO HOL_BANKING_DE.SOURCE.LOCATIONS (LOCATION_ID, LOCATION_NAME)
  FROM @HOL_BANKING_DE.SOURCE.HOL_DATA FILES = ('locations.csv')
  FILE_FORMAT = (FORMAT_NAME = 'HOL_BANKING_DE.SOURCE.HOL_CSV') ON_ERROR = 'ABORT_STATEMENT';
COPY INTO HOL_BANKING_DE.SOURCE.CUSTOMERS (CUSTOMER_ID, SEGMENT, LOCATION_ID)
  FROM @HOL_BANKING_DE.SOURCE.HOL_DATA FILES = ('customers.csv')
  FILE_FORMAT = (FORMAT_NAME = 'HOL_BANKING_DE.SOURCE.HOL_CSV') ON_ERROR = 'ABORT_STATEMENT';
COPY INTO HOL_BANKING_DE.SOURCE.TRANSACTIONS
  (TRANSACTION_ID, CUSTOMER_ID, TRANSACTION_TIME, AMOUNT, PRODUCT_CATEGORY, CHANNEL, STATUS)
  FROM @HOL_BANKING_DE.SOURCE.HOL_DATA FILES = ('transactions.csv')
  FILE_FORMAT = (FORMAT_NAME = 'HOL_BANKING_DE.SOURCE.HOL_CSV') ON_ERROR = 'ABORT_STATEMENT';
SELECT 'LOCATIONS' AS TABLE_NAME, COUNT(*) AS ROW_COUNT FROM HOL_BANKING_DE.SOURCE.LOCATIONS
UNION ALL SELECT 'CUSTOMERS', COUNT(*) FROM HOL_BANKING_DE.SOURCE.CUSTOMERS
UNION ALL SELECT 'TRANSACTIONS', COUNT(*) FROM HOL_BANKING_DE.SOURCE.TRANSACTIONS;
SELECT SUM(IFF(STATUS = 'COMPLETED', AMOUNT, 0)) AS NET_SPEND FROM HOL_BANKING_DE.SOURCE.TRANSACTIONS;

